// BuiltinIDs lists the built-in rules that can be exported.
func BuiltinIDs() []string {
	ids := make([]string, 0, len(builtinPolicies))
	for id := range builtinPolicies {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	return ids
}
